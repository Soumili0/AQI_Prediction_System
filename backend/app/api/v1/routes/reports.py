"""
Reports Routes  —  /api/v1/reports/
GET  /                   — list user reports
POST /prediction-history — generate & download prediction CSV or PDF
POST /analytics          — generate & download analytics CSV or PDF
GET  /<id>               — report metadata
"""

from flask import Blueprint, request, jsonify, send_file
from flask_jwt_extended import jwt_required, get_jwt_identity
from io import BytesIO
from app import limiter
from app.services import report_service

reports_bp = Blueprint("reports", __name__)


@reports_bp.get("/")
@jwt_required()
def list_reports():
    """
    List all reports generated by the current user.
    ---
    tags: [Reports]
    security:
      - BearerAuth: []
    responses:
      200:
        description: List of report metadata
    """
    user_id = int(get_jwt_identity())
    return jsonify({"reports": report_service.list_reports(user_id)}), 200


@reports_bp.post("/prediction-history")
@jwt_required()
@limiter.limit("20 per hour")
def generate_prediction_report():
    """
    Generate and download a prediction history report.
    ---
    tags: [Reports]
    security:
      - BearerAuth: []
    requestBody:
      content:
        application/json:
          schema:
            type: object
            properties:
              format:    { type: string, enum: [csv, pdf], default: csv }
              city:      { type: string }
              date_from: { type: string, example: "2024-01-01" }
              date_to:   { type: string, example: "2024-12-31" }
    responses:
      200:
        description: File download
    """
    user_id = int(get_jwt_identity())
    data    = request.get_json(silent=True) or {}
    fmt     = data.get("format", "csv").lower()
    filters = {k: data.get(k) for k in ("city", "date_from", "date_to") if data.get(k)}

    if fmt == "pdf":
        content   = report_service.generate_pdf_prediction_history(user_id, filters)
        mime      = "application/pdf"
        filename  = f"prediction_history_{user_id}.pdf"
    else:
        content   = report_service.generate_csv_prediction_history(user_id, filters)
        mime      = "text/csv"
        filename  = f"prediction_history_{user_id}.csv"

    return send_file(
        BytesIO(content),
        mimetype=mime,
        as_attachment=True,
        download_name=filename,
    )


@reports_bp.post("/analytics")
@jwt_required()
@limiter.limit("20 per hour")
def generate_analytics_report():
    """
    Generate and download an analytics report.
    ---
    tags: [Reports]
    security:
      - BearerAuth: []
    requestBody:
      content:
        application/json:
          schema:
            type: object
            properties:
              format: { type: string, enum: [csv, pdf], default: pdf }
              city:   { type: string }
              days:   { type: integer, default: 30 }
    responses:
      200:
        description: File download
    """
    user_id = int(get_jwt_identity())
    data    = request.get_json(silent=True) or {}
    fmt     = data.get("format", "pdf").lower()
    city    = data.get("city")
    days    = int(data.get("days", 30))

    if fmt == "csv":
        content  = report_service.generate_csv_analytics(city=city, days=days)
        mime     = "text/csv"
        filename = "aqi_analytics.csv"
    else:
        content  = report_service.generate_pdf_analytics(city=city, days=days)
        mime     = "application/pdf"
        filename = "aqi_analytics.pdf"

    return send_file(BytesIO(content), mimetype=mime,
                     as_attachment=True, download_name=filename)
